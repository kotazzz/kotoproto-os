const Bitmap kSystem[] = {
    {"visor", 54, 38, 7, kSystem_visor, sizeof(kSystem_visor)},
};
const int kSystemCount = static_cast<int>(sizeof(kSystem) / sizeof(kSystem[0]));

const Bitmap* find_system(std::string_view id) {
  for (int i = 0; i < kSystemCount; ++i) {
    if (id == kSystem[i].id) {
      return &kSystem[i];
    }
  }
  return nullptr;
}

